#!/bin/bash
# Removes KDrop for the current user. Settings in ~/.config/kdrop.json are kept.
systemctl --user stop kdrop-send kdrop-receive kdrop-browse kdrop-radio-off.timer kdrop-radio 2>/dev/null
command -v kpackagetool6 >/dev/null && kpackagetool6 -t Plasma/Applet -r io.github.erdeemaydin.kdrop
D="${XDG_DATA_HOME:-$HOME/.local/share}"
rm -f "$HOME/.local/bin/kdrop" "$D/kio/servicemenus/kdrop.desktop" \
      "$D/applications/kdrop-receive.desktop" "$D/applications/kdrop-browse.desktop" \
      "$D"/nemo/actions/kdrop-*.nemo_action
for dir in "$D/nautilus/scripts/Send via AirDrop" "${XDG_CONFIG_HOME:-$HOME/.config}/caja/scripts/Send via AirDrop"; do
    [ -d "$dir" ] && grep -l "generated by kdrop" "$dir"/* 2>/dev/null | xargs -r -d '\n' rm -f && rmdir "$dir" 2>/dev/null
done
echo "KDrop removed. Delete ~/.config/kdrop.json too if you want to forget its settings."
